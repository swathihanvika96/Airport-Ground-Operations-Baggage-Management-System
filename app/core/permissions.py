"""Role-based access control: which roles may perform which group of operations.

SUPER_ADMIN is implicitly allowed everywhere (handled in `require_roles`).
"""
from app.utils.enums import UserRole as R

ALL_ROLES = frozenset(R)
ADMIN = frozenset({R.SUPER_ADMIN})
MANAGEMENT = frozenset({R.SUPER_ADMIN, R.AIRPORT_OPERATIONS_MANAGER})
FLIGHT_OPS = MANAGEMENT | {R.FLIGHT_OPERATIONS_OFFICER}


class Permissions:
    USER_ADMIN = ADMIN | {R.AIRPORT_OPERATIONS_MANAGER}
    AIRPORT_MANAGE = MANAGEMENT
    TERMINAL_MANAGE = MANAGEMENT
    FLIGHT_MANAGE = FLIGHT_OPS
    FLIGHT_STATUS_UPDATE = FLIGHT_OPS | {R.GATE_AGENT}
    GATE_MANAGE = FLIGHT_OPS
    GATE_ASSIGN = FLIGHT_OPS | {R.GATE_AGENT}
    COUNTER_MANAGE = FLIGHT_OPS
    COUNTER_ASSIGN = FLIGHT_OPS | {R.CHECKIN_AGENT}
    PASSENGER_MANAGE = MANAGEMENT | {R.CHECKIN_AGENT, R.GATE_AGENT, R.FLIGHT_OPERATIONS_OFFICER}
    CHECKIN = MANAGEMENT | {R.CHECKIN_AGENT}
    BOARDING = MANAGEMENT | {R.GATE_AGENT}
    BAGGAGE_REGISTER = MANAGEMENT | {R.CHECKIN_AGENT, R.BAGGAGE_HANDLING_STAFF}
    BAGGAGE_TRACK = MANAGEMENT | {R.BAGGAGE_HANDLING_STAFF, R.GROUND_STAFF_SUPERVISOR, R.CHECKIN_AGENT}
    BAGGAGE_SCREEN = MANAGEMENT | {R.BAGGAGE_HANDLING_STAFF, R.GROUND_STAFF_SUPERVISOR}
    STAFF_MANAGE = MANAGEMENT | {R.GROUND_STAFF_SUPERVISOR}
    TASK_MANAGE = MANAGEMENT | {R.GROUND_STAFF_SUPERVISOR, R.FLIGHT_OPERATIONS_OFFICER}
    TASK_EXECUTE = TASK_MANAGE | {R.BAGGAGE_HANDLING_STAFF, R.MAINTENANCE_STAFF}
    TURNAROUND_MANAGE = MANAGEMENT | {R.GROUND_STAFF_SUPERVISOR, R.FLIGHT_OPERATIONS_OFFICER}
    EQUIPMENT_MANAGE = MANAGEMENT | {R.GROUND_STAFF_SUPERVISOR, R.MAINTENANCE_STAFF}
    EQUIPMENT_ASSIGN = MANAGEMENT | {R.GROUND_STAFF_SUPERVISOR, R.FLIGHT_OPERATIONS_OFFICER}
    MAINTENANCE = MANAGEMENT | {R.MAINTENANCE_STAFF}
    INCIDENT_REPORT = ALL_ROLES
    INCIDENT_MANAGE = MANAGEMENT | {R.GROUND_STAFF_SUPERVISOR, R.FLIGHT_OPERATIONS_OFFICER}
    DELAY_MANAGE = FLIGHT_OPS
    RESOURCE_ALLOCATE = FLIGHT_OPS | {R.GROUND_STAFF_SUPERVISOR}
    DASHBOARD_VIEW = ALL_ROLES
    REPORTS_VIEW = MANAGEMENT | {R.FLIGHT_OPERATIONS_OFFICER, R.GROUND_STAFF_SUPERVISOR}
    AUDIT_VIEW = MANAGEMENT
    NOTIFICATION_BROADCAST = MANAGEMENT | {R.FLIGHT_OPERATIONS_OFFICER}


# Roles that receive operational notifications by topic
NOTIFY_FLIGHT_OPS = [R.AIRPORT_OPERATIONS_MANAGER, R.FLIGHT_OPERATIONS_OFFICER]
NOTIFY_GATE = [R.GATE_AGENT, R.FLIGHT_OPERATIONS_OFFICER]
NOTIFY_CHECKIN = [R.CHECKIN_AGENT]
NOTIFY_BAGGAGE = [R.BAGGAGE_HANDLING_STAFF, R.GROUND_STAFF_SUPERVISOR]
NOTIFY_GROUND = [R.GROUND_STAFF_SUPERVISOR, R.AIRPORT_OPERATIONS_MANAGER]
NOTIFY_INCIDENT = [R.AIRPORT_OPERATIONS_MANAGER, R.GROUND_STAFF_SUPERVISOR, R.FLIGHT_OPERATIONS_OFFICER]

# Roles a user can pick when self-registering (privileged roles need an admin)
SELF_REGISTRATION_ROLES = frozenset({
    R.FLIGHT_OPERATIONS_OFFICER, R.GROUND_STAFF_SUPERVISOR, R.BAGGAGE_HANDLING_STAFF,
    R.CHECKIN_AGENT, R.GATE_AGENT, R.MAINTENANCE_STAFF,
})
